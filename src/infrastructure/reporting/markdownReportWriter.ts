import type { Finding } from "../../domain/cleanup.js";
import type { EvaluationResult } from "../../domain/evaluation.js";
import type { Solution } from "../../domain/solution.js";
import type { IReportWriter } from "../../ports/services.js";

/** A fixed template, so every report reads the same and costs no model tokens. */
export class MarkdownReportWriter implements IReportWriter {
  render(solution: Solution, evaluations: EvaluationResult[], summary?: string, openIssues: Finding[] = []): string {
    const rows = evaluations.map((e) => `| ${e.kind} | ${this.status(e)} | ${this.cell(e.digest)} |`);
    return [
      `## ${solution.summary}`,
      "",
      `**Request:** ${solution.prompt}`,
      `**Solution:** \`${solution.id}\` (${solution.state})`,
      ...(summary ? ["", summary.trim()] : []),
      "",
      "### Evaluation",
      "",
      "| Gate | Result | Details |",
      "|---|---|---|",
      ...(rows.length ? rows : ["| none | not run | |"]),
      "",
      ...(openIssues.length ? [
        "### Open SonarQube issues",
        "",
        "| Severity | Rule | Location | Message |",
        "|---|---|---|---|",
        ...openIssues.map((f) => `| ${f.severity} | ${f.rule} | \`${f.file}${f.line ? `:${f.line}` : ""}\` | ${this.cell(f.message)} |`),
        "",
      ] : []),
      "Generated by aisdlc. A human reviews this change before it merges.",
      "",
    ].join("\n");
  }

  private status(e: EvaluationResult): string {
    if (e.isSkipped) return "skipped";
    return e.passed ? "passed" : "**failed**";
  }

  /** Keeps a digest on one table row. */
  private cell(text: string): string {
    return text.replace(/\r?\n/g, " ").replace(/\|/g, "\\|");
  }
}
