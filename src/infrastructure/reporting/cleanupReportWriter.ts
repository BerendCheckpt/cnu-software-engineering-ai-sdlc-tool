import {
  FINDING_CATEGORIES, findingKey, isSecurityFinding, ValidPr, type CleanupBatch, type CleanupRun, type Finding,
  type GateSnapshot,
} from "../../domain/cleanup.js";
import { bySeverity, normalizeSeverity, SEVERITIES } from "../../domain/quality.js";
import type { DocReference, ICleanupReportWriter } from "../../ports/services.js";

/** Fixed templates, so the plan and the PR body read the same every time and cost no model tokens. */
export class CleanupReportWriter implements ICleanupReportWriter {
  plan(run: CleanupRun, batches: CleanupBatch[]): string {
    const counts = FINDING_CATEGORIES
      .map((c) => [c, run.baseline.findings.filter((f) => f.category === c).length] as const)
      .filter(([, n]) => n > 0)
      .map(([c, n]) => `${c} ${n}`);
    return [
      `# Clean-up plan for ${run.repository}`,
      "",
      `Run \`${run.id}\` on branch \`${run.branch}\`, from \`${run.baseBranch}\`.`,
      "",
      "## Before",
      "",
      ...this.gateLines(run.baseline.gates),
      `- findings: ${counts.length ? counts.join(", ") : "none"}`,
      ...(run.baseline.limitations ?? []).map((l) => `- not covered: ${l}`),
      "",
      "## Batches",
      "",
      "| # | Category | Findings | Files |",
      "|---|---|---|---|",
      ...batches.map((b) => `| ${b.number} | ${b.category} | ${b.category === "format" ? "formatters, no model" : b.findings.length} | ${this.files(b)} |`),
      "",
      "## Automode",
      "",
      "The batches run one after another without stopping. A batch that breaks a test that passed before, or adds a",
      "new finding, is not committed. A batch that changes or deletes tests, changes dependencies or touches",
      "security-sensitive code is committed and flagged in the pull request, where a human reviews everything.",
      "",
    ].join("\n");
  }

  report(run: CleanupRun, batches: CleanupBatch[], docs: Map<string, DocReference> = new Map(), sonarProject?: string): string {
    const fixed = ValidPr.fixed(run.baseline, run.reference);
    const escalated = batches.filter((b) => b.status === "escalated");
    const rows = batches.map((b) => {
      const gates = b.gates.map((g) => g.gate).join(", ") || "none";
      const outcome = b.status === "done" ? (b.commitSha ? `\`${b.commitSha.slice(0, 8)}\`` : b.note ?? "")
        : b.status === "escalated"
          ? `${b.commitSha ? `\`${b.commitSha.slice(0, 8)}\`, ` : ""}${this.cell(b.note ?? "escalated")}`
          : `skipped: ${this.cell(b.note ?? "")}`;
      return `| ${b.number} | ${b.category} | ${b.category === "format" ? "-" : b.findings.length} | ${gates} | ${outcome} |`;
    });
    return [
      `## Clean-up of ${run.repository}`,
      "",
      `${fixed.length} of ${run.baseline.findings.length} findings fixed, with no test that passed before failing now ` +
        "and no new findings.",
      ...(run.baseline.limitations ?? []).map((l) => `Not covered: ${l}`),
      "",
      ...this.changelog(fixed, batches),
      ...this.security(run, batches, fixed, docs),
      "### Gates",
      "",
      "| Gate | Before | After |",
      "|---|---|---|",
      ...run.baseline.gates.map((before) => {
        const after = run.reference.gates.find((g) => g.kind === before.kind);
        return `| ${before.kind} | ${this.gate(before)} | ${after ? this.gate(after) : "not run"} |`;
      }),
      "",
      "### Batches",
      "",
      "| # | Category | Findings | Flagged | Outcome |",
      "|---|---|---|---|---|",
      ...rows,
      "",
      ...(escalated.length ? [
        "### Escalated to a human",
        "",
        "These batches still had findings open after their last try, and the engineer chose this PR with an issue " +
          "for each finding left. A batch's partial fix is in this PR only when it made nothing worse:",
        "",
        ...escalated.map((b) => `- Batch ${b.number} (${b.category}): ${b.note?.replace(/^escalated: /, "") ?? ""}`),
        "",
      ] : []),
      ...this.leftForLater(run, sonarProject),
      "Generated by aisdlc in automode. No change was approved on the way: this PR is the review.",
      "",
    ].join("\n");
  }

  /** SonarQube findings below the run's level: only their count per severity and where they are. */
  private leftForLater(run: CleanupRun, sonarProject: string | undefined): string[] {
    const left = run.leftForLater;
    if (!left.length) return [];
    const counts = SEVERITIES
      .map((s) => [s, left.filter((f) => normalizeSeverity(f.severity) === s).length] as const)
      .filter(([, n]) => n > 0);
    return [
      "### Left for later",
      "",
      `This clean-up ran at severity level \`${run.level}\`. These SonarQube findings were below it and were not ` +
        `touched; they stay in the SonarQube project ${sonarProject ? `\`${sonarProject}\`` : "of this run"}:`,
      "",
      ...counts.map(([s, n]) => `- ${s}: ${n}`),
      "",
      "Please create GitHub issues in this repository for them, so they can be picked up later.",
      "",
    ];
  }

  /** Every fixed finding, most severe first, with the commit that fixed it. */
  private changelog(fixed: Finding[], batches: CleanupBatch[]): string[] {
    if (!fixed.length) return [];
    return [
      "### Changelog",
      "",
      "| Severity | Category | Rule | Location | Commit |",
      "|---|---|---|---|---|",
      ...bySeverity(fixed).map((f) => {
        const batch = this.batchOf(f, batches);
        const commit = batch?.commitSha ? `\`${batch.commitSha.slice(0, 8)}\`${batch.gates.length ? " ⚠" : ""}` : "as a side effect";
        return `| ${normalizeSeverity(f.severity)} | ${f.category} | ${this.cell(f.rule)} | ${this.location(f)} | ${commit} |`;
      }),
      "",
      "⚠: the batch changed tests, dependencies or security-sensitive code; see Security concerns.",
      "",
    ];
  }

  /** Every security finding, fixed or not, and every change that needs a close look. */
  private security(run: CleanupRun, batches: CleanupBatch[], fixed: Finding[], docs: Map<string, DocReference>): string[] {
    const findings = bySeverity(run.baseline.findings.filter(isSecurityFinding));
    const fixedKeys = new Set(fixed.map(findingKey));
    const flagged = batches.filter((b) => b.status === "done" && b.gates.length);
    if (!findings.length && !flagged.length) return ["### Security concerns", "", "None found.", ""];
    return [
      "### Security concerns",
      "",
      ...(findings.length ? [
        "| Severity | Source | Rule | Location | Status | Docs |",
        "|---|---|---|---|---|---|",
        ...findings.map((f) => {
          const batch = this.batchOf(f, batches);
          const status = fixedKeys.has(findingKey(f))
            ? `fixed${batch?.commitSha ? ` in \`${batch.commitSha.slice(0, 8)}\`` : ""}`
            : batch?.status === "escalated" ? this.cell(batch.note ?? "escalated") : "still open";
          const doc = docs.get(f.rule);
          return `| ${normalizeSeverity(f.severity)} | ${f.source} | ${this.cell(f.rule)} | ${this.location(f)} | ${status} | ` +
            `${doc ? `[${this.cell(doc.heading)}](${doc.url})` : "-"} |`;
        }),
        "",
        ...(docs.size ? [] : ["No pulled official docs matched these rules. Pull them with `aisdlc docs request <id>`.", ""]),
      ] : []),
      ...(flagged.length ? [
        "Review these changes closely:",
        "",
        ...flagged.map((b) => `- Batch ${b.number} (${b.category}, \`${b.commitSha?.slice(0, 8) ?? "-"}\`): ` +
          b.gates.map((g) => `${g.gate}: ${g.files.map((f) => `\`${f}\``).join(", ")}`).join("; ")),
        "",
      ] : []),
    ];
  }

  private batchOf(f: Finding, batches: CleanupBatch[]): CleanupBatch | undefined {
    const key = findingKey(f);
    return batches.find((b) => b.findings.some((g) => findingKey(g) === key));
  }

  private location(f: Finding): string {
    return `\`${this.cell(f.file)}${f.line ? `:${f.line}` : ""}\``;
  }

  private gateLines(gates: GateSnapshot[]): string[] {
    return gates.map((g) => `- ${g.kind}: ${this.gate(g)}`);
  }

  private gate(g: GateSnapshot): string {
    if (g.skipped) return "skipped";
    const tests = g.tests ? `, ${g.tests.total - g.tests.failed}/${g.tests.total} tests` : "";
    const coverage = g.coverage !== undefined ? `, coverage ${g.coverage}%` : "";
    return `${g.passed ? "passed" : "failed"}${tests}${coverage}`;
  }

  private files(b: CleanupBatch): string {
    const files = [...new Set(b.findings.map((f) => f.file))];
    return this.cell(files.length > 3 ? `${files.slice(0, 3).join(", ")} +${files.length - 3}` : files.join(", "));
  }

  private cell(text: string): string {
    return text.replace(/\r?\n/g, " ").replace(/\|/g, "\\|");
  }
}
